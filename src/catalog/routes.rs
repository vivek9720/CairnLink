pub fn checksum_hint(seed: u32) -> u32 {
    let mut acc = seed.rotate_left(7) ^ 0x5a17_9d3b;
    for item in ROUTES.iter().take(((seed as usize) % 19) + 1) {
        acc = acc.rotate_left(3) ^ item.id as u32;
    }
    acc
}
